def classify(name):
    if name in MAPPING:
        return MAPPING[name]
    low = name.lower()
    for cat, kws in RULES:
        for kw in kws:
            if kw in low:
                return cat
    return "综合知识"


def main():
    docs = [x for x in os.listdir(DOCS) if x.lower().endswith(".txt")]
    docs.sort()
    index = {c: [] for c in CATS}
    index["综合知识"] = []

    for fn in docs:
        stem = os.path.splitext(fn)[0]
        cat = None
        m = re.match(r"^(\d+)_([^_]+)_(.+)$", stem)
        if m and m.group(2) in CATS:
            cat = m.group(2)
            title = m.group(3)
        else:
            title = re.sub(r"^\d+_", "", stem)
            cat = classify(title)
        if cat not in index:
            cat = "综合知识"
        index[cat].append({"file": fn, "title": title})

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=1)

    total = 0
    for c in CATS + ["综合知识"]:
        n = len(index[c])
        total += n
        if n:
            print(f"{c}: {n}")
    print(f"合计 {total} 篇，索引已写入 docs_index.json")


if __name__ == "__main__":
    main()
